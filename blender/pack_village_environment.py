"""Validate Blender environment renders, optimize for the game and emit local-file-safe metadata."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageChops
import json
ROOT=Path(__file__).resolve().parents[1];out=ROOT/'assets'/'village'
meta=json.loads((out/'manifest.json').read_text());placements=json.loads((out/'placements.json').read_text())
for name in ['ground']+meta['assets']:
 path=out/(name+'.png')
 with Image.open(path) as image:
  image=image.convert('RGBA');assert image.size==((2048,2048) if name=='ground' else (512,512)),path
  bounds=image.getchannel('A').point(lambda x:255 if x>220 else 0).getbbox();assert bounds,path
  if name!='ground':
   assert bounds[0]>0 and bounds[1]>0 and bounds[2]<512 and bounds[3]<512,(name,bounds)
   # Only the faint tail of a contact shadow may reach the render border.
   # Feather it to zero so sprites never leave a hard rectangular shadow edge.
   mask=Image.new('L',image.size,0);draw=ImageDraw.Draw(mask)
   for inset in range(25):draw.rectangle((inset,inset,511-inset,511-inset),fill=round(255*inset/24))
   # Match shadow contrast to the Canvas ambient lighting; opaque geometry stays opaque.
   alpha=image.getchannel('A').point(lambda a:round(a*(.6+.4*(a/255)**6)))
   image.putalpha(ImageChops.multiply(alpha,mask))
  image.save(out/(name+'.webp'),quality=88,method=4)
data={'meta':meta,'placements':placements}
(ROOT/'scripts'/'village-kit-data.js').write_text('// Generated by blender/pack_village_environment.py\nwindow.VillageKitData='+json.dumps(data,separators=(',',':'))+';\n')
print('Validated and optimized',len(meta['assets']),'Blender props and ground.')
